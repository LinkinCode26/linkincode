const isPlainObject = (value) =>
  value !== null && typeof value === "object" && !Array.isArray(value);

function deepMerge(base, extra) {
  const out = { ...base };
  Object.keys(extra).forEach((key) => {
    out[key] =
      isPlainObject(base?.[key]) && isPlainObject(extra[key])
        ? deepMerge(base[key], extra[key])
        : extra[key];
  });
  return out;
}

export function withEcommerceAdmin(dict, extra) {
  const { solutions } = dict;
  const { simulator } = solutions;
  return {
    ...dict,
    solutions: {
      ...solutions,
      simulator: {
        ...simulator,
        // Lo que ya existe en translations.js tiene prioridad; extra solo
        // aporta las claves que faltan.
        ecommerce: deepMerge(extra, simulator.ecommerce),
      },
    },
  };
}

